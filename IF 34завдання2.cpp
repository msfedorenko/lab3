#include <iostream>
#include <cmath>

using namespace std;

// Окрема процедура для Завдання 2 (Варіант 34)
void task_geom34() {
    double r;
    double x, y;

    cout << "=== ЗАВДАННЯ 2 (Варіант 34 - Геометрія) ===" << endl;
    cout << "Введіть радіус кола r (r > 0): ";
    cin >> r;

    // Перевірка коректності введення радіуса
    if (cin.fail() || r <= 0) {
        cerr << "Помилка: Некоректне значення радіуса!" << endl;
        return;
    }

    cout << "Введіть координати точки через пробіл (x y): ";
    cin >> x >> y;

    // Перевірка коректності введення координат
    if (cin.fail()) {
        cerr << "Помилка: Некоректні координати!" << endl;
        return;
    }

    // Математична модель для 34 варіанта (світло-зелена область на рисунку):
    // Перевірка приналежності до кола (x^2 + y^2 <= r^2) у першій чверті, обмежена бісектрисою (y <= x)[cite: 7, 10]
    double distSq = x * x + y * y;
    bool inCircle = (distSq <= r * r);
    
    bool inArea = inCircle && (x >= 0) && (y >= 0) && (y <= x);

    if (inArea) {
        cout << "Точка (" << x << ", " << y << ") ПОТРАПЛЯЄ у фігуру 34-го варіанта." << endl;
    } else {
        cout << "Точка (" << x << ", " << y << ") НЕ потрапляє у фігуру." << endl;
    }
}

int main() {
    task_geom34();
    return 0;
}